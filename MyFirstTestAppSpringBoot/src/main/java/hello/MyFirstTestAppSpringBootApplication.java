//Указывает, что класс MyFirstTestAppSpringBootApplication принадлежит пакету hello.
//В файловой системе это соответствует папке src/main/java/hello/.
//Пакеты нужны, чтобы группировать классы, избегать конфликтов имён и управлять видимостью (например, private в пределах пакета).
package hello;
//Главный класс Spring Boot, который отвечает за запуск приложения, настройку контекста, автоконфигурацию, веб‑сервер и т.д.
import org.springframework.boot.SpringApplication;
//Аннотация, которая объединяет несколько других аннотаций (об этом ниже). Она говорит Spring Boot: «этот класс—точка входа и содержит конфигурацию».
//комбо» из трёх аннотаций:
//
//@Configuration—класс содержит бины и настройки (может использоваться вместо XML‑конфигураций).
//@EnableAutoConfiguration—включает автоконфигурацию: Spring Boot сам подтягивает нужные компоненты (веб‑модуль, JDBC, JPA и т.п.) на основе зависимостей в проекте.
//@ComponentScan—автоматически сканирует все классы с аннотациями (@Controller, @Service, @Repository и т.д.) в пакете этого класса и его подпакетах и регистрирует их как бины.
//Таким образом, одной аннотацией мы говорим: «это Spring Boot‑приложение, используй автоконфигурацию и сканируй компоненты в этом пакете».
import org.springframework.boot.autoconfigure.SpringBootApplication;


//Это обычный Java‑класс, но благодаря @SpringBootApplication он становится «точкой входа» и конфигурационным классом для всего приложения.
@SpringBootApplication(scanBasePackages = {"hello"})
public class MyFirstTestAppSpringBootApplication {

    //Это стандартный метод main, с которого JVM начинает выполнение программы.
	public static void main (String[] args) {

        SpringApplication.run(MyFirstTestAppSpringBootApplication.class, args);

        //Что происходит при этом вызове:
        //
        //Создание контекста приложения. Spring Boot создаёт ApplicationContext—контейнер, где будут храниться все бины (компоненты) вашего приложения.
        //Автоконфигурация. На основе зависимостей (Maven/Gradle) Spring Boot решает, какие модули включить: например, если есть зависимость spring-boot-starter-web, он поднимет встроенный Tomcat и настроит MVC.
        //Сканирование компонентов. Благодаря @ComponentScan, Spring находит все @Controller, @Service и другие компоненты в пакете и регистрирует их в контексте.
        //Обработка аргументов командной строки. Аргументы args передаются в приложение—их можно использовать для настройки (например, указать порт, профиль, путь к файлу конфигурации).
        //Запуск встроенного сервера. Если это веб‑приложение, стартует встроенный сервер (Tomcat, Jetty или Undertow).
        //Публикация событий и инициализация. Запускаются CommandLineRunner/ApplicationRunner, выполняются миграции БД (Flyway/Liquibase), инициализируются кэши и т.д.
        //Приложение готово к работе. После этого приложение слушает запросы на настроенном порту (по умолчанию—8080).
	}

}
